-- Rexus Phase 2: vault (environments, secrets, secret versions).

CREATE TABLE environments (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id uuid NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name       text NOT NULL CHECK (name ~ '^[a-z][a-z0-9_-]{0,29}$'),
    position   int NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, name)
);

-- Existing projects get the default environments.
INSERT INTO environments (project_id, name, position)
SELECT p.id, e.name, e.position
FROM projects p
CROSS JOIN (VALUES ('dev', 0), ('staging', 1), ('prod', 2)) AS e (name, position);

CREATE TABLE secrets (
    id              uuid PRIMARY KEY,       -- generated by the app: it is part of the encryption context
    environment_id  uuid NOT NULL REFERENCES environments (id) ON DELETE CASCADE,
    name            text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    expires_on      date,
    notes           text NOT NULL DEFAULT '',
    tags            text[] NOT NULL DEFAULT '{}',
    custom_fields   jsonb NOT NULL DEFAULT '{}', -- NOT encrypted: names/values for provider, owner, etc.
    current_version int NOT NULL DEFAULT 1,
    created_by      uuid REFERENCES users (id) ON DELETE SET NULL,
    updated_by      uuid REFERENCES users (id) ON DELETE SET NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (environment_id, name)
);
CREATE INDEX secrets_expires_idx ON secrets (expires_on) WHERE expires_on IS NOT NULL;

-- One row per value. Old versions are kept; restoring creates a new version.
CREATE TABLE secret_versions (
    secret_id   uuid NOT NULL REFERENCES secrets (id) ON DELETE CASCADE,
    version     int NOT NULL,
    ciphertext  bytea NOT NULL,             -- value encrypted with a per-version data key (AES-256-GCM)
    wrapped_key bytea NOT NULL,             -- that data key, encrypted with the master key
    created_by  uuid REFERENCES users (id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (secret_id, version)
);
